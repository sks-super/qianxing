-- rockPrims.lua —— 「图腾柱」图元数据（第 40 批起用它替代石头）
--
-- 来源：用户导出的「超限素材组」脚本（1 个静态图 → 1043 个旋转图元）
--   `local ROOT` + 18 字段：{asset,x,y,w,h,pivot…,scale…,rotZ,r,g,b,a}
--   画布 1280×1280、中心原点、y 向上、颜色直接给 RGB。
--
-- 转换（_tmp/gen_rock_prims.mjs）：
--   ① 按旋转后的包围盒归一化成 **高 = 1**，原点 = 柱脚中点，y 向上
--      → 运行时只要一个「柱高 px」，所有笔的 x/y/w/h 都乘它
--   ② **真值剪影 + 逐行边界开运算**（第 41 批）：全 1043 笔叠出 alpha 覆盖，
--      取每行左右边界，做形态学开运算（半径 8.0% 柱高）+ 均值收尾 →
--      一条干净的柱体轮廓。开运算 = 腐蚀再膨胀，**削凸 + 填凹**，
--      比它窄的尖角/毛刺全被削平，比它窄的凹口全被填平 —— 这才是「光滑」。
--      ★ 原素材边缘本来就是毛的（凸起、斜伸的角），而精简后大笔的直角会直接暴露出来；
--        轮廓不平滑，怎么加笔都是「边缘多出来的角」。
--   ③ **每笔收进轮廓**：矩形覆盖率的 97% 落在轮廓内才留，否则二分收缩 w/h；
--      缩到 30% 还大半在外 → 整笔丢掉（那才是真正「多出来的角」）。
--      本次 1043 笔 → 保留 991（128 笔缩过）、丢弃 52 笔。
--   ④ **覆盖率贪心 + 补洞**（200×500 网格，只留能盖出尚未盖住的格子的笔），
--      保证轮廓内没有缝 —— 否则柱子会露出背景的草地。
--      ⚠️ 别关这一步：全部石头 × 1043 笔 = 7 万多个控件，真机必崩。
--   ⑤ 再按「亮度 × 面积 × alpha」补细节：前 18 笔进**核心层**（BASE），
--      后 54 笔进**辉光层**（GLOW）。
--      ★ 细节层不是装饰：那些半透明的橙金亮缝与符文**不新增面积、只叠亮**，
--        纯覆盖率一条都收不进来 —— 少了它柱子就是一团黑块。
--   ⑥ 两组各自按**源顺序**输出 —— 叠色顺序就是原图的绘制顺序，改顺序会改变明暗
--
-- 数据格式：{x, y, w, h, rot, rgb, alpha} × N，单位「柱高」
--   x : 相对柱身中线的偏移（左右）    y : **离柱脚**的高度（0 = 柱脚，1 = 柱顶）
--   都是**中心点**，不是左上角。
--
-- ★ 分两层的用意见 config.DEFAULT_PILLAR_GLOW：关掉辉光层就只用 BASE（控件少 35%）。
-- ⚠️ 不要手改数值；换素材请重跑 _tmp/gen_rock_prims.mjs 覆盖本文件。
