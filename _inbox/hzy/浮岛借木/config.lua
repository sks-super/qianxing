-- ----------------------------------------------------------------
-- ★ 美术素材的「内容占比」→ 控件缩放系数
--   素材是 1024×1024 的正方形，但真正有内容的部分只占中间一块；
--   要让「内容」正好压在格子上，控件尺寸就得放大。系数 = 画布尺寸 / 内容尺寸：
--
--     草地.png   顶面 900×900 / 1024  →  w = h = 1024/900 = 1.138, dy = 0
--                ★ 顶面必须是**正方形**（水平/垂直边），铺到正交网格上才严丝合缝。
--                  AI 生成的地块多半是「等距菱形」顶面，铺上去会变成菱形格纹 ——
--                  所以这张素材改用 _tools/make_grass_tile.py 程序化生成。
--     树木.png   内容 403×563 / 1024  →  内容做 **1 格高** → 控件 1.819×1.819 格
--     人物.png   内容 410×600 / 1024  →  内容做 **1 格高** → 控件 1.707×1.707 格
--
--   ★ 树木与人物都是「只定高、按原比例缩放」：控件放大系数取 1024 / 内容高，
--     于是内容正好 1 格高，宽度自然落到 403/563 = 0.72 格（树）、410/600 = 0.68 格（人）。
--     这样既满足「一格高」，又不会把立绘拉扁 —— 一旦宽高比被拉变形，
--     窄条形的树会变成一坨方块，比「矮一点」难看得多。
--     想让树占满整格，得重新出一张 1:1 的画，而不是在这里硬拉。
--
--   其余「岛缘描边 / 侧面厚度 / 水下投影 / 倒下的树 / 树根」均由脚本画
--   （两种路径同源），素材里不带，所以换素材只需要改这一处缩放系数。
--
--   dy = 把内容摆到正确位置所需的竖向偏移（单位：格，正 = 控件中心往上挪）：
--     草地 = 0（顶面本来就居中）
