-- ================================================================
-- ★ 取关卡配置（1 起始）；越界返回 nil
-- ================================================================
function M.getLevelConfig(index)
    local idx = tonumber(index)
    if not idx then return nil end
    idx = math.floor(idx)
    if idx < 1 or idx > #M.LEVELS then return nil end
    return M.LEVELS[idx]
end

-- ================================================================
-- ★ 关卡总数
-- ================================================================
function M.getLevelCount()
    return #M.LEVELS
end

return M
