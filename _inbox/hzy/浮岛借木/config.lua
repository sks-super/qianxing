-- ================================================================
-- ★ 高度模型（单位：格）
--   小岛地面 = 0；人物高 1 格；立着的树高 1 格。
--   ★★ 倒下的树有**两个**高度，这是本作能玩起来的关键：
--       压在陆地上 → 0.5 格（半格高，跨不上去）→ 只能「推」
--       浮在水面上 → 0.25 格（吃水一半）→ 够低，能踩上去当踏脚石
--       —— 一个高度解决不了「既推得动、又踩得上」这对矛盾，
--          所以「推」与「踩」的分界就落在 0.25 与 0.5 之间。
--   ★ 小人最大跨步 = 0.25 格：只有树根（0.25）和浮在水面的树干（0.25）够低能踩，
--     半格高的树干与一格的树 / 石头都跨不上去 —— 于是「撞上去 = 推动它」。
--   ★ 一切可视物体都只占**一格**（1×1）：立着的树 / 倒下的树 / 树根 / 石头。
--     没有「木桩」这个概念了 —— 立着与倒下只是同一棵树的两个状态。
--   ★ 立着的树有两种，行为一样、来历不同（运行时用 `tree.bare` 区分）：
--       真树   = 关卡数据 `trees` 里的那棵，有树冠；撞倒在原地留 0.25 格树根。
--       树干   = 小人在正面推倒下的树时把它**竖起来**的那根（`bare = true`）：
--                造型与倒下的树同源（没有叶子），再撞倒它也**不会留下树根**。
--     玩法上唯一的差别就是「倒完留不留树根」，所以推立起来的那根不能当成新树。
--   ★ 撞倒与推（侧推 / 正推）都会让小人**顺势前进一格**（撞倒 = 站到树根上，
--     推 = 站到木头原来占的那一格），能不能前进仍按 0.25 格的跨步上限判一次。
--   ★ 「躺 / 立」两态在**画面上必须一眼分得开** —— 这是玩法可读性的前提：
--       躺 = 长而扁（1.0 × 0.5 格）、深一点偏灰的旧木色、贴地一条暗边、两端切面带年轮；
--       立 = 窄而高（0.36 × 1.0 格）、亮一点偏暖的新木色、竖向受光、顶端一圈亮切面、
--             根部扎进土里的一小撮土堆 + 暗影。
--     切换两态时还有一段过渡补间（倒下 = 甩过头再落定 + 落地扬尘；
--     立起 = 往上过冲一下再站稳），见 level.lua 的 `animateObject`。
