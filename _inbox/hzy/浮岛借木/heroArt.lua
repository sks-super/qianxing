-- _tools/restyle_hero.py 接力生成；两个脚本都别手改，改发色只改 13/14 两行 hex）
--
-- ★ 为什么要这样存：千星脚本只能实例化矩形 / 图片 / 文本 / 容器控件，
--   没有「把一张 PNG 画出来」的接口。所以角色不是引用图片，而是
--   **用 15 种颜色、几百块纯色矩形拼出来的像素画** —— 换朝向就是换一套矩形。
--
-- ★ 坐标单位：网格格（不是像素）。整个网格 = COLS × ROWS 格，
--   运行时一块的边长 = cellSize / ROWS，于是内容正好 1 格高，
--   而且格子边长怎么自适应都不会把角色拉变形（像素恒为正方形）。
-- ★ 四张共用同一个网格与同一套调色板：转身时脚底不动、配色不跳。
--
-- ★ 调色板 0-12 是量化出的原色（按亮度排序）；13 起是 _tools/restyle_hero.py
--   后补的「头发色」—— 量化会把银灰发和白裙压成同一个白，补两档才看得出是头发。
--   补发色时按「格」判色、再重做行 RLE 合并，块数会略增（S 146→165），
--   但「哪些格是实心」完全不变 —— 轮廓与清晰度零改动。
--   要调发色只改 13/14 两行 hex；脸按 FACE_ROWS/FACE_COLS 保护、保持原色。
--
-- RECT 项 = { x, y, w, h, c }：左上角格坐标 + 宽高（格）+ 调色板索引。
--   y 从上往下数（0 = 头顶那行）；绘制时脚本再翻成 UI 的向上为正。
-- ================================================================

