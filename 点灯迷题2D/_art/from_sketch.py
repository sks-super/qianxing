BG = (26, 34, 56)


def parse(text):
    rows = [r for r in text.strip("\n").split("\n")]
    assert len(rows) == N, f"行数 {len(rows)} != 16"
    out = []
    for i, r in enumerate(rows):
        assert len(r) == N, f"第 {i} 行长度 {len(r)} != 16: {r}"
        assert set(r) <= {"#", "."}, f"第 {i} 行有非法字符"
        out.append([1 if ch == "#" else 0 for ch in r])
    return out


def label_regions(mask):
    """白区四连通标号；返回 lab, 外区标号"""
    lab = [[-1] * N for _ in range(N)]
    cur = 0
    for y in range(N):
        for x in range(N):
            if mask[y][x] == 0 and lab[y][x] == -1:
                q = deque([(x, y)])
                lab[y][x] = cur
                while q:
                    cx, cy = q.popleft()
                    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                        nx, ny = cx + dx, cy + dy
                        if 0 <= nx < N and 0 <= ny < N and mask[ny][nx] == 0 and lab[ny][nx] == -1:
                            lab[ny][nx] = cur
                            q.append((nx, ny))
                cur += 1
    outside = lab[0][0]
    return lab, cur, outside


def bleed(lab, mask):
    """黑线格归属到邻近白区（反复扩散），这样 64 版能被颜色填满"""
    changed = True
    while changed:
        changed = False
        for y in range(N):
            for x in range(N):
                if mask[y][x] == 1 and lab[y][x] == -1:
                    votes = {}
                    for dy in (-1, 0, 1):
                        for dx in (-1, 0, 1):
                            nx, ny = x + dx, y + dy
                            if 0 <= nx < N and 0 <= ny < N and lab[ny][nx] >= 0:
                                votes[lab[ny][nx]] = votes.get(lab[ny][nx], 0) + 1
                    if votes:
                        lab[y][x] = max(votes, key=votes.get)
                        changed = True
    return lab


def region_order(lab, nreg, outside):
    """按质心 y 从上到下排序（同 y 再按 x），外区不参与"""
    info = {}
    for y in range(N):
        for x in range(N):
            l = lab[y][x]
            if l < 0:
                continue
            s = info.setdefault(l, [0, 0, 0])
            s[0] += y
            s[1] += x
            s[2] += 1
    items = [(l, s[0] / s[2], s[1] / s[2]) for l, s in info.items() if l != outside]
    items.sort(key=lambda t: (t[1], t[2]))
    return [t[0] for t in items]


def shade(c, f):
    return tuple(max(0, min(255, int(v * f))) for v in c)


def render16(mask):
    img = Image.new("RGB", (N, N), (255, 255, 255))
    px = img.load()
    for y in range(N):
        for x in range(N):
            if mask[y][x]:
                px[x, y] = (16, 16, 16)
    return img


def render64(mask, pal):
    """白区上色 + 黑线保留（按 2px 重绘）。

    ★ 关键：黑线【不能】当成"被填色的区域"去做 bleed。
      那样 1px 的眼睛/鼻子会被并进大面积色块 → 特征全消失（猫脸糊成一坨、钥匙剩一个方块）。
      正确做法：白格按分区上色，黑格在 4x4 块的中心画 2x2 的线 → 线条反而比 16 版更细更干净。
    """
    lab, nreg, outside = label_regions(mask)
    order = region_order(lab, nreg, outside)
    color_of = {}
    for i, l in enumerate(order):
        color_of[l] = pal[i % len(pal)]
    color_of[outside] = BG

    K = 4
    n = N * K
    img = Image.new("RGB", (n, n), BG)
    px = img.load()

    # ① 白区填色 + 纵向明暗
    for y in range(N):
        for x in range(N):
            if mask[y][x] != 0:
                continue
            l = lab[y][x]
            base = color_of.get(l, BG)
            for yy in range(K):
                t = yy / float(K - 1)
                f = 1.0 if l == outside else (1.14 - 0.26 * t)
                for xx in range(K):
                    px[x * K + xx, y * K + yy] = shade(base, f)

    # ② 线旁 1px 压暗（让线条有厚度，不至于硬邦邦）
    for y in range(N):
        for x in range(N):
            if mask[y][x] != 1:
                continue
            for yy in range(K):
                for xx in range(K):
                    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                        nx, ny = x * K + xx + dx, y * K + yy + dy
                        if 0 <= nx < n and 0 <= ny < n:
                            cx, cy = nx // K, ny // K
                            if not (0 <= cx < N and 0 <= cy < N) or mask[cy][cx] == 0:
                                base = color_of.get(lab[cy][cx], BG) if 0 <= cx < N and 0 <= cy < N else BG
                                cur = px[nx, ny]
                                if cur != base:
                                    continue
                                px[nx, ny] = shade(base, 0.72)

    # ③ 黑线：4x4 块中心 2x2 + 向相邻黑格补桥（否则格与格之间断成虚线）
    INK = (16, 16, 16)
    for y in range(N):
        for x in range(N):
            if mask[y][x] != 1:
                continue
            bx, by = x * K, y * K
            for yy in (1, 2):
                for xx in (1, 2):
                    px[bx + xx, by + yy] = INK
            if x + 1 < N and mask[y][x + 1] == 1:      # 右接
                for xx in (3, 4):
                    for yy in (1, 2):
                        px[bx + xx, by + yy] = INK
            if y + 1 < N and mask[y + 1][x] == 1:      # 下接
                for yy in (3, 4):
                    for xx in (1, 2):
                        px[bx + xx, by + yy] = INK

    return img


def main():
    os.makedirs(os.path.join(OUT, "16"), exist_ok=True)
    os.makedirs(os.path.join(OUT, "64"), exist_ok=True)
    try:
        font = ImageFont.truetype(r"C:/Windows/Fonts/msyh.ttc", 15)
    except Exception:
        font = ImageFont.load_default()

    t16, t64, stats = [], [], []
    for name, text in SKETCHES.items():
        mask = parse(text)
        black = sum(sum(r) for r in mask)
        img16 = render16(mask)
        img64 = render64(mask, PALETTE[name])
        img16.save(os.path.join(OUT, "16", f"{name}_raw16.png"))
        img64.save(os.path.join(OUT, "64", f"{name}_raw64.png"))
        img16.resize((N * 16, N * 16), Image.NEAREST).save(os.path.join(OUT, "16", f"{name}.png"))
        img64.resize((N * 4 * 4, N * 4 * 4), Image.NEAREST).save(os.path.join(OUT, "64", f"{name}.png"))
        stats.append((name, black))

        def tile(img, sc, text_):
            w, h = img.size
            big = img.resize((w * sc, h * sc), Image.NEAREST)
            c = Image.new("RGB", (big.size[0], big.size[1] + 24), (18, 22, 34))
            c.paste(big, (0, 24))
            ImageDraw.Draw(c).text((6, 5), text_, font=font, fill=(220, 230, 245))
            return c

        t16.append(tile(img16, 11, f"{CN[name]} {black}/256"))
        t64.append(tile(img64, 3, f"{CN[name]}"))

    def sheet(tiles, cols, path):
        tw, th = tiles[0].size
        rows = (len(tiles) + cols - 1) // cols
        c = Image.new("RGB", (cols * (tw + 8) + 8, rows * (th + 8) + 8), (12, 15, 24))
        for i, t in enumerate(tiles):
            c.paste(t, (8 + (i % cols) * (tw + 8), 8 + (i // cols) * (th + 8)))
        c.save(path)
        return c.size

    print("sheet16", sheet(t16, 5, os.path.join(OUT, "sheet_sketch_16.png")))
    print("sheet64", sheet(t64, 5, os.path.join(OUT, "sheet_sketch_64.png")))
    print("\n黑线占比：")
    for name, black in stats:
        print(f"  {CN[name]:<4}({name:<10}) {black:>2}/256 = {black/256*100:5.1f}%")


if __name__ == "__main__":
    main()
