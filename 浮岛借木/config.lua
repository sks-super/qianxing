--   其余「岛缘描边 / 侧面厚度 / 水下投影」均由脚本画（两种路径同源），素材里不带，
--   所以换素材只需要改这一处缩放系数。
--
--   dy = 把内容摆到正确位置所需的竖向偏移（单位：格，正 = 控件中心往上挪）：
